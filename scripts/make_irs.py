"""Generate the room impulse responses for Voice effects ▸ Space → library/ir/<id>.wav (48 kHz stereo, CC0, ours).

Each space = deterministic early reflections + a decaying, darkening noise tail (low frequencies ring longer than highs),
decorrelated left/right. Energy-normalised so every space sits at a similar level; amount is set per clip.
python scripts/make_irs.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfilt

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "library" / "ir"
SR = 48000

# id: (name, rt60 s, predelay ms, early reflections (count, spread ms), tail brightness Hz, echo (ms, gain) or None)
SPACES = {
    "small_room":  ("Small room", 0.35, 3, (8, 14), 7000, None),
    "living_room": ("Living room", 0.55, 6, (10, 22), 6000, None),
    "car":         ("Car", 0.14, 1.5, (12, 6), 5200, None),
    "cafe":        ("Café", 0.85, 10, (12, 30), 7200, None),
    "classroom":   ("Classroom", 1.05, 12, (12, 34), 6500, None),
    "stairwell":   ("Stairwell", 2.1, 14, (16, 40), 9000, None),
    "hall":        ("Concert hall", 2.4, 26, (14, 60), 5500, None),
    "church":      ("Church", 4.0, 38, (14, 90), 4500, None),
    "forest":      ("Forest", 0.7, 25, (5, 120), 3400, None),
    "stadium":     ("Stadium", 2.8, 60, (8, 140), 4200, (260, 0.35)),
}


def make(rt60, predelay_ms, er, bright, echo, seed):
    rng = np.random.default_rng(seed)
    n = int(SR * min(6.0, rt60 * 1.6 + predelay_ms / 1000 + 0.05))
    t = np.arange(n) / SR
    out = np.zeros((2, n), np.float32)
    pd = int(predelay_ms / 1000 * SR)
    count, spread = er
    for ch in range(2):
        noise = rng.standard_normal(n).astype(np.float32)
        lo = sosfilt(butter(2, min(bright, 0.45 * SR) / (SR / 2), "low", output="sos"), noise)
        hi = noise - lo
        env_lo = np.exp(-6.91 * t / rt60)
        env_hi = np.exp(-6.91 * t / (rt60 * 0.55))              # highs die faster → the tail darkens
        tail = (lo * env_lo + 0.5 * hi * env_hi).astype(np.float32)
        tail[:pd] = 0
        onset = np.clip((t - predelay_ms / 1000) / 0.012, 0, 1)  # soft build-up after the pre-delay
        tail *= onset
        er_sig = np.zeros(n, np.float32)
        for k in range(count):
            dt = pd + int(rng.uniform(0.5, spread) / 1000 * SR)
            if dt < n:
                er_sig[dt] += rng.choice([-1, 1]) * (0.8 ** k) * rng.uniform(0.5, 1.0)
        if echo:
            ms, g = echo
            d = pd + int(ms / 1000 * SR)
            if d < n:
                er_sig[d] += g * (1 if ch == 0 else 0.8)
        sig = 0.55 * tail + er_sig
        out[ch] = sig
    out /= np.sqrt((out ** 2).sum(axis=1, keepdims=True)) + 1e-9   # unit energy per channel
    return out * 0.5


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    meta = {}
    for i, (sid, (name, rt60, pd, er, bright, echo)) in enumerate(SPACES.items()):
        ir = make(rt60, pd, er, bright, echo, seed=100 + i)
        peak = np.abs(ir).max()
        wavfile.write(OUT / f"{sid}.wav", SR, (ir.T / max(peak, 1e-9) * 0.98 * 32767).astype(np.int16))
        meta[sid] = {"name": name, "rt60": rt60, "file": f"library/ir/{sid}.wav", "gain": round(float(peak / 0.98), 6)}
        print(f"{sid:12s} {name:14s} RT60 {rt60}s  {ir.shape[1] / SR:.2f}s")
    (OUT / "spaces.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    (OUT / "README.txt").write_text("Room impulse responses generated by scripts/make_irs.py (synthetic, free to use - CC0).\n", encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
