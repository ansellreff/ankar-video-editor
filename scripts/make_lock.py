"""Write requirements-lock.txt: every package of the working .venv (exact versions) with the SHA-256 of its Windows
wheel from PyPI, so Setup installs exactly these files (`pip install --require-hashes --only-binary=:all:`) and
nothing else. Run after changing requirements.txt:  python -m scripts.make_lock
Optional voice engine:  .venv-tts/Scripts/python -m scripts.make_lock --out requirements-tts-lock.txt
Only wheels for Windows 64-bit / CPython 3.12 (or pure-Python) are accepted — no source builds on users' PCs."""
from __future__ import annotations

import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / (sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else "requirements-lock.txt")
SKIP = {"pip"}                                   # setuptools stays: torch needs it on Python 3.12
DEV_ONLY = {"pytest", "iniconfig", "pluggy", "pygments", "colorama"}   # kept: tests are part of the download
OK_TAG = re.compile(r"-(cp312-cp312|cp312-abi3|cp3\d+-abi3|py3-none|py2\.py3-none|cp312-none)-(win_amd64|any)\.whl$")


def frozen() -> list[tuple[str, str]]:
    out = subprocess.run([sys.executable, "-m", "pip", "freeze", "--all"], capture_output=True, text=True, check=True).stdout
    pkgs = []
    for line in out.splitlines():
        if "==" in line:
            n, v = line.strip().split("==", 1)
            if n.lower() not in SKIP:
                pkgs.append((n, v))
    return pkgs


def wheel_hashes(name: str, ver: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{ver}/json", timeout=30) as r:
        files = json.load(r)["urls"]
    return [f["digests"]["sha256"] for f in files if f["packagetype"] == "bdist_wheel" and OK_TAG.search(f["filename"])]


def main():
    lines, bad = ["# Generated by scripts/make_lock.py — exact packages + wheel hashes for Windows 64-bit, Python 3.12.",
                  "# Setup installs ONLY these files:  pip install --require-hashes --only-binary=:all: -r requirements-lock.txt"], []
    for n, v in sorted(frozen(), key=lambda x: x[0].lower()):
        h = wheel_hashes(n, v)
        if not h:
            bad.append(f"{n}=={v}")
            continue
        lines.append(f"{n}=={v} " + " ".join(f"--hash=sha256:{x}" for x in h))
    if bad:
        sys.exit("No Windows wheel on PyPI for: " + ", ".join(bad))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name}: {len(lines) - 2} packages")


if __name__ == "__main__":
    main()
