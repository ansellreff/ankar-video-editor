"""Database: Neon Postgres on Vercel (env DATABASE_URL, set by the Neon integration), SQLite file for local tests.

What is stored — and nothing else:
  users     username, password hash (scrypt), email (AES-GCM encrypted, optional), created, latest downloaded version +
            date, admin authenticator secret (encrypted, admin only), sign-in failure counter / lock time
  sessions  SHA-256 of the session token (never the token), user id, expiry
  resets    SHA-256 of a one-time email code, expiry, tries
  limits    rate-limit counters (keyed by username or "global", never by IP address)
  version_downloads  anonymous count per version"""
from __future__ import annotations

import os
import sqlite3
import threading
from pathlib import Path

URL = os.environ.get("DATABASE_URL") or os.environ.get("POSTGRES_URL") or ""
PG = URL.startswith(("postgres://", "postgresql://"))
LOCAL = Path(os.environ.get("ANKAR_SITE_DB") or Path(__file__).resolve().parents[2] / "local.db")

_lock = threading.RLock()
_conn = None
_ready = False

ID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if PG else "INTEGER PRIMARY KEY AUTOINCREMENT"
SCHEMA = [
    f"""CREATE TABLE IF NOT EXISTS users (
        id {ID},
        username TEXT NOT NULL,
        username_lc TEXT NOT NULL UNIQUE,
        pw_hash TEXT NOT NULL,
        email_enc TEXT,
        created_at BIGINT NOT NULL,
        last_version TEXT,
        last_download_at BIGINT,
        totp_enc TEXT,
        totp_pending_enc TEXT,
        totp_last_step BIGINT NOT NULL DEFAULT 0,
        failed INTEGER NOT NULL DEFAULT 0,
        locked_until BIGINT NOT NULL DEFAULT 0,
        disabled INTEGER NOT NULL DEFAULT 0)""",
    """CREATE TABLE IF NOT EXISTS sessions (
        token_hash TEXT PRIMARY KEY,
        user_id BIGINT NOT NULL,
        created_at BIGINT NOT NULL,
        expires_at BIGINT NOT NULL,
        admin_until BIGINT NOT NULL DEFAULT 0)""",
    "CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id)",
    """CREATE TABLE IF NOT EXISTS resets (
        user_id BIGINT PRIMARY KEY,
        code_hash TEXT NOT NULL,
        expires_at BIGINT NOT NULL,
        tries INTEGER NOT NULL DEFAULT 0,
        sent_at BIGINT NOT NULL)""",
    """CREATE TABLE IF NOT EXISTS limits (
        k TEXT PRIMARY KEY,
        start BIGINT NOT NULL,
        n INTEGER NOT NULL)""",
    """CREATE TABLE IF NOT EXISTS version_downloads (
        version TEXT PRIMARY KEY,
        n BIGINT NOT NULL)""",
]


def _connect():
    if PG:
        import psycopg
        from psycopg.rows import dict_row
        # prepare_threshold=None: Neon's pooled endpoint (PgBouncer, transaction mode) can't keep prepared statements
        return psycopg.connect(URL, autocommit=True, prepare_threshold=None, row_factory=dict_row, connect_timeout=10)
    c = sqlite3.connect(str(LOCAL), check_same_thread=False, isolation_level=None)
    c.row_factory = sqlite3.Row
    c.execute("PRAGMA journal_mode=WAL")
    return c


def _sql(s: str) -> str:
    return s.replace("?", "%s") if PG else s


def q(sql: str, args: tuple = (), one: bool = False):
    """Run one statement. Returns a list of dicts (or one dict / None with one=True)."""
    global _conn, _ready
    with _lock:
        for attempt in (0, 1):
            try:
                if _conn is None:
                    _conn = _connect()
                if not _ready:
                    for s in SCHEMA:
                        _conn.execute(s)
                    _ready = True
                cur = _conn.execute(_sql(sql), args)
                rows = [dict(r) for r in cur.fetchall()] if cur.description else []
                return (rows[0] if rows else None) if one else rows
            except Exception as e:  # noqa: BLE001 — a dropped serverless connection: reconnect once
                if attempt or not _is_conn_error(e):
                    raise
                try:
                    _conn.close()
                except Exception:  # noqa: BLE001
                    pass
                _conn = None


def _is_conn_error(e: Exception) -> bool:
    return type(e).__name__ in ("OperationalError", "InterfaceError")


def reset_for_tests(path: Path):
    """Point at a fresh SQLite file (tests only)."""
    global _conn, _ready, LOCAL, PG
    with _lock:
        if _conn is not None:
            _conn.close()
        _conn, _ready, LOCAL, PG = None, False, path, False
